#!/usr/bin/env python3
# 从 mockup 的 P / FONT 生成固件头文件（palette.h / glyph.h），保证与定稿视觉逐像素一致
import os
OUT = os.path.expanduser("~/esp32/ticker/src")
os.makedirs(OUT, exist_ok=True)

P = {
 'k':(8,8,16),'l':(144,192,232),'s':(160,232,232),
 'n':(16,24,48),'N':(24,36,64),'N3':(32,52,88),
 't':(40,64,104),
 'w':(24,104,120),'W':(40,144,160),'W3':(80,192,200),'W4':(160,232,232),
 'g':(24,120,56),'G':(88,200,88),'G3':(168,232,120),
 'r':(168,32,32),'R':(240,80,48),'R3':(248,144,96),
 'y':(160,104,0),'Y':(248,184,0),'Y3':(248,224,88),
 'u':(104,112,136),'U':(176,184,200),'U3':(248,248,248),
 'b':(48,96,168),'B':(72,128,200),
 # 早盘暖色（第一交易时段）
 'e':(48,24,12),'E':(72,36,16),'E3':(96,52,24),'eG':(128,80,36),
 # 加密盘：紫黑
 'x':(26,10,44),'X':(42,18,66),'X3':(58,26,92),'xG':(78,36,124),
}
def rgb565(c):
    r,g,b = c
    return ((r>>3)<<11) | ((g>>2)<<5) | (b>>3)

names = {
 'k':'INK','n':'BG0','N':'BG1','N3':'BG2','t':'GRID',
 'w':'SEA0','W':'SEA1','W3':'SEA2','W4':'SEA3',
 'g':'UP_D','G':'UP','G3':'UP_HI',
 'r':'DN_D','R':'DN','R3':'DN_HI',
 'y':'GOLD_D','Y':'GOLD','Y3':'GOLD_HI',
 'u':'UI_D','U':'UI','U3':'UI_HI',
 'b':'WHALE_D','B':'WHALE','l':'WHALE_L','s':'SPOUT',
 'e':'WARM0','E':'WARM1','E3':'WARM2','eG':'WARM_GRID',
 'x':'CRY0','X':'CRY1','X3':'CRY2','xG':'CRY_GRID',
}
lines = ["// 自动生成 by tools/gen_assets.py — 与 mockup 定稿同色，勿手改",
         "#pragma once","#include <stdint.h>",""]
for k,n in names.items():
    lines.append(f"static const uint16_t PAL_{n} = 0x{rgb565(P[k]):04X};")
lines.append("")
lines.append("static inline uint16_t PAL_UP_BY(bool up){ return up ? PAL_UP : PAL_DN; }")
open(os.path.join(OUT,"palette.h"),"w").write("\n".join(lines)+"\n")

FONT = {
'0':["111","101","101","101","111"],'1':["010","110","010","010","111"],
'2':["111","001","111","100","111"],'3':["111","001","111","001","111"],
'4':["101","101","111","001","001"],'5':["111","100","111","101","111"],
'6':["111","100","111","101","111"],'7':["111","001","010","010","010"],
'8':["111","101","111","101","111"],'9':["111","101","111","001","111"],
'.':["000","000","000","000","010"],'!':["100","100","100","000","100"],
'?':["111","001","011","000","010"],'%':["101","001","010","100","101"],
'/':["001","001","010","100","100"],'=':["000","111","000","111","000"],
'-':["000","000","111","000","000"],'+':["000","010","111","010","000"],
'B':["110","101","110","101","110"],'S':["011","100","011","001","110"],
'x':["000","101","010","101","101"],'A':["010","101","111","101","101"],
'C':["011","100","100","100","011"],'D':["110","101","101","101","110"],
'E':["111","100","110","100","111"],'F':["111","100","110","100","100"],
'G':["011","100","101","101","011"],'H':["101","101","111","101","101"],
'I':["111","010","010","010","111"],'J':["001","001","001","101","010"],
'K':["101","101","110","101","101"],'L':["100","100","100","100","111"],
'M':["101","111","111","101","101"],'N':["101","111","111","111","101"],
'O':["010","101","101","101","010"],'P':["110","101","110","100","100"],
'Q':["010","101","101","110","011"],'R':["110","101","110","101","101"],
'T':["111","010","010","010","010"],'U':["101","101","101","101","111"],
'V':["101","101","101","101","010"],'W':["101","101","111","111","101"],
'X':["101","101","010","101","101"],'Y':["101","101","010","010","010"],
'Z':["111","001","010","100","111"],
' ':["000","000","000","000","000"],
}
g = ["// 自动生成 by tools/gen_assets.py — 3x5 点阵，与 mockup 同字形，勿手改",
     "#pragma once","#include <stdint.h>","",
     "// 每个字形 5 行，每行低 3 位（bit2..bit0），按列从左到右；未定义字符为全 0",
     "static const uint8_t GLYPH5[128][5] = {"]
for code in range(128):
    ch = chr(code)
    if ch in FONT:
        rows = []
        for r in FONT[ch]:
            v = 0
            for i,c in enumerate(r):
                if c == '1': v |= (1 << (2-i))
            rows.append(v)
        g.append(f"  {{{rows[0]},{rows[1]},{rows[2]},{rows[3]},{rows[4]}}},   // {code} '{ch}'")
    else:
        g.append("  {0,0,0,0,0},")
g.append("};")
g.append("")
g.append("// 字符宽度（3px 字模 + 1px 字距）")
g.append("static inline uint8_t glyphW(uint8_t sc){ return 4*sc; }")
open(os.path.join(OUT,"glyph.h"),"w").write("\n".join(g)+"\n")
print("wrote palette.h + glyph.h ->", OUT)
